import 'reflect-metadata';
import pg from 'pg';
import assert from 'node:assert/strict';
import { NestFactory } from '@nestjs/core';
import { AppModule } from '../src/app.module';
import { DomainExceptionFilter } from '../src/transport/domain-exception.filter';
import { createIsolatedQaDatabase } from './qa-isolated-database';
import { runMigrations } from '@qeynox/persistence';
const qa=await createIsolatedQaDatabase(); process.env.DATABASE_URL=qa.url; process.env.QEYNOX_ALLOW_REGISTRATION='true';
let app: Awaited<ReturnType<typeof NestFactory.create>> | undefined;
try {
  await runMigrations(qa.url); app=await NestFactory.create(AppModule,{logger:false}); app.useGlobalFilters(new DomainExceptionFilter()); await app.listen(0,'127.0.0.1');
  const base='http://127.0.0.1:'+(app.getHttpServer().address() as {port:number}).port;
  const call=async (path:string, body?:unknown, headers:Record<string,string>={}) => { const res=await fetch(base+path,{method:body===undefined?'GET':'POST',headers:{'content-type':'application/json',...headers},...(body===undefined?{}:{body:JSON.stringify(body)})}); return {status:res.status, body:await res.json() as any}; };
  const register=async(email:string)=>{const u=await call('/v1/auth/register',{email,password:'qa-soul-passphrase',workspaceName:'QA soul'}); assert.equal(u.status,201); return {authorization:'Bearer '+u.body.token,'x-qeynox-workspace':u.body.workspaceId};};
  const h=await register('soul-a@example.invalid'), h2=await register('soul-b@example.invalid');
  await call('/v1/soul/onboarding/start',{locale:'en'},h);
  await call('/v1/soul/onboarding/answer',{step:'WELCOME',value:'begin'},h);
  await call('/v1/soul/onboarding/answer',{step:'LANGUAGE',value:'en'},h);
  const no=await call('/v1/soul/onboarding/consent',{granted:false},h); assert.equal(no.body.step,'FIRST_OBJECTIVE'); assert.equal(no.body.consent.granted,false);
  const bad=await call('/v1/soul/onboarding/mission',{objective:'no'},h); assert.equal(bad.status,400);
  assert.equal((await call('/v1/soul/onboarding',undefined,h)).body.status,'IN_PROGRESS');
  assert.equal((await call('/v1/operations',undefined,h)).body.length,0);
  const db = new pg.Pool({connectionString:qa.url});
  try {
    await db.query("CREATE FUNCTION qa_reject_operation() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RAISE EXCEPTION ''qa failure''; END'");
    await db.query('CREATE TRIGGER qa_reject BEFORE INSERT ON operations FOR EACH ROW EXECUTE FUNCTION qa_reject_operation()');
    const failure=await call('/v1/soul/onboarding/mission',{objective:'Test first objective'},h); assert.equal(failure.status,500);
    await db.query('DROP TRIGGER qa_reject ON operations');
    assert.equal((await call('/v1/soul/onboarding',undefined,h)).body.status,'IN_PROGRESS');
    assert.equal((await call('/v1/operations',undefined,h)).body.length,0);
    const user=(await db.query("SELECT id FROM identity_users WHERE email='soul-a@example.invalid'")).rows[0].id;
    await db.query("INSERT INTO identity_workspaces(id,name,created_by) VALUES ('qa-workspace-other','Other',$1)",[user]);
    await db.query("INSERT INTO identity_memberships(id,user_id,workspace_id,role,status) VALUES ('qa-member-other',$1,'qa-workspace-other','OWNER','ACTIVE')",[user]);
    const other={...h,'x-qeynox-workspace':'qa-workspace-other'};
    assert.equal((await call('/v1/soul/onboarding',undefined,other)).body.status,'NOT_STARTED');
  } finally { await db.end(); }
  const [a,b]=await Promise.all([call('/v1/soul/onboarding/mission',{objective:'Test first objective'},h),call('/v1/soul/onboarding/mission',{objective:'Test first objective'},h)]);
  assert.equal(a.status,201); assert.equal(b.status,201); assert.equal(a.body.id,b.body.id);
  assert.equal((await call('/v1/operations',undefined,h)).body.length,1);
  assert.equal((await call('/v1/soul/onboarding',undefined,h)).body.status,'COMPLETED');
  assert.equal((await call('/v1/operations',undefined,h2)).body.length,0);
  assert.equal((await call('/v1/soul/onboarding',undefined,h2)).body.status,'NOT_STARTED');
  assert.equal((await call('/v1/soul/context',undefined,h)).body.length,0);
  await call('/v1/soul/onboarding/start',{locale:'en'},h2);
  await call('/v1/soul/onboarding/answer',{step:'WELCOME',value:'begin'},h2);
  await call('/v1/soul/onboarding/answer',{step:'LANGUAGE',value:'en'},h2);
  const granted=await call('/v1/soul/onboarding/consent',{granted:true},h2); assert.equal(granted.body.consent.granted,true);
  await call('/v1/soul/onboarding/answer',{step:'ACTIVITY',value:'Private activity'},h2);
  assert.equal((await call('/v1/soul/onboarding/pause',{},h2)).body.status,'PAUSED');
  assert.equal((await call('/v1/soul/onboarding/resume',{},h2)).body.status,'IN_PROGRESS');
  assert.equal((await call('/v1/soul/consents/'+granted.body.consent.consentId+'/revoke',{},h2)).status,201);
  assert.equal((await call('/v1/soul/context',undefined,h2)).body.length,0);
  const restored=await call('/v1/soul/onboarding/consent',{granted:true},h2);
  assert.equal((await call('/v1/soul/onboarding',undefined,h2)).body.consent.granted,true);
  assert.equal((await call('/v1/soul/consents/'+restored.body.consent.consentId+'/revoke',{},h2)).status,201);
  for (const step of ['OBJECTIVES','NEEDS','PREFERENCES']) assert.equal((await call('/v1/soul/onboarding/skip',{step},h2)).status,201);
  assert.equal((await call('/v1/soul/onboarding/mission',{objective:'Mission after revocation'},h2)).status,201);
  assert.equal((await call('/v1/soul/context',undefined,h2)).body.length,0);
  console.log('Soul refusal, atomic mission, retry and workspace isolation: PASS');
} finally { if (app) await app.close(); await qa.drop(); }
